"""Turn exhibitors.json and exhibitor_tags.json into the frontend's and backend's exhibitor data.

Tags and buyer sectors come from retag_exhibitors.py. Stalls listed as "ASSOCIATION" in the visitor
guide have no booth to visit and are left out of the stall list.
"""
import json
import re
from collections import Counter
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parent / "client/src/data/exhibitors.ts"
MAX_TAGS = 5

NAME_FIXES = {  # OCR slips in the source, corrected against the visitor guide.
    "17 OPTO-ELECTRONICS INC.": "I7 OPTO-ELECTRONICS INC.",
    "МЕНТА HITECH INDUSTRIES LIMITED": "MEHTA HITECH INDUSTRIES LIMITED",
    "ECOPTIK|CHINALTD": "ECOPTIK (CHINA) LTD",
    "FLUENCE TECHNOLOGY SP. Z O.0.": "FLUENCE TECHNOLOGY SP. Z O.O.",
}


def clean_name(record):
    name = re.sub(r"\s+", " ", record["name"].strip())
    return NAME_FIXES.get(name, name)


def booth_code(raw):
    m = re.match(r"([A-Za-z]{2})\s*(\d+)", raw.strip())
    return f"{m[1].upper()} {m[2]}"


def booth_list(record):
    codes = []
    for raw in record["booths"]:
        for part in raw.split("/"):
            code = booth_code(part)
            if code not in codes:
                codes.append(code)
    return codes


def main():
    data = json.loads((HERE / "exhibitors.json").read_text())
    tags = json.loads((HERE / "exhibitor_tags.json").read_text())
    rows, skipped = [], []
    for slug, record in sorted(data.items(), key=lambda kv: clean_name(kv[1]).lower()):
        booths = booth_list(record)
        if not booths:
            skipped.append(clean_name(record))
            continue
        rows.append(
            {
                "id": f"ex-{slug}",
                "name": clean_name(record),
                "description": record["description"] or "",
                "hall": booths[0][:2],
                "booth": booths[0],
                "otherBooths": booths[1:],
                "city": record["city"] or "",
                "country": record["country"] or "",
                "products": record["products"][:12],
                "tags": tags[slug]["tags"],
                "industries": tags[slug]["industries"],
            }
        )

    (HERE.parent / "backend/data").mkdir(parents=True, exist_ok=True)
    (HERE.parent / "backend/data/exhibitors.json").write_text(json.dumps(rows, ensure_ascii=False, indent=1))

    body = ",\n".join("  " + json.dumps(r, ensure_ascii=False) for r in rows)
    OUT.write_text(
        "// GENERATED by data/build_frontend_data.py from data/exhibitors.json. Do not edit by hand.\n"
        "// Names and booths: LASER World of PHOTONICS INDIA 2026 visitor guide. Descriptions and products\n"
        "// were enriched from public web sources; tags and sectors were inferred by an AI model.\n"
        "import type { Exhibitor } from '../types';\n\n"
        f"export const EXHIBITORS: readonly Exhibitor[] = [\n{body},\n] as Exhibitor[];\n"
    )

    print("stalls", len(rows), "skipped (no booth)", skipped)
    print("no tags:", [r["name"] for r in rows if not r["tags"]])
    print("no sectors:", [r["name"] for r in rows if not r["industries"]])
    print("tags per stall:", sorted(Counter(len(r["tags"]) for r in rows).items()))
    for name, n in Counter(t for r in rows for t in r["tags"]).most_common():
        print(f"  {n:4} {name}")
    print("sectors:", Counter(s for r in rows for s in r["industries"]).most_common())
    print("rows:", sorted(Counter(r["hall"] for r in rows).items()))
    print("distinct tag sets:", len({tuple(sorted(r["tags"])) for r in rows}))
    print("odd names:", [r["name"] for r in rows if re.search(r"[^\x00-\x7f]|\|", r["name"])])


main()
